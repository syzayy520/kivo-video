package com.kivo.cinema.net

/**
 * 273 v31：**让路决策** —— 拖动期间，播放主链路的预读要不要停手。
 *
 * ## 它为什么独立成一个文件
 * "要不要让路"是**策略**（看闸门、看落点窗口），
 * "让路怎么做"是**动作**（掐掉在飞的块、暂停生产）。
 * 生产循环（[OriginPrefetchPump]）只管"什么时候读、往哪写" ——
 * 策略与循环是**两种变化原因**：改阈值不该动循环，改循环不该动阈值。
 *
 * ## v30 的教训（真机三连，同一段落点偏移）
 * v30 给"开始让路"加了个前提：**环里还得有 ≥1/4 容量的缓冲**，
 * 想法是"缓冲见底时播放会卡 ⇒ 不能让路"。真机测出来的恰恰相反：
 *
 *  · **环几乎是空的** —— 内核读得比源站快，缓冲一落地就被抽走
 *    ⇒ 那个前提几乎永远不成立 ⇒ 让路闸**一次都没开过**（真机 v30：开 0 次）；
 *  · 拖动落点那一跳因此被**别人**抢带宽：落点窗口有效速率
 *    **632–730 KB/s**（v30）vs **1,038–2,316 KB/s**（v29）；
 *  · 同一个落点偏移（1,886,093,814）上，落点窗口从 **2,566 ms**（v29）
 *    拖到 **6,830 ms**（v30）⇒ 拖动之后白屏更久。
 *
 * 【根因】v30 的"环见底就恢复"让路只撑了 **402 ms**，主链路的预读线程
 * 立刻又开新块 —— 而它开的新块**与落点窗口重叠**
 * （真机 v30-win-2：落点窗口 1,886,028,278..1,890,288,118，
 * 主链路同时在拉 1,862,134,812 / 1,866,329,116 / 1,870,523,420 三块 4 MiB）。
 * 源站带宽是**封顶**的 ⇒ 两边一起下 ⇒ 两边都慢。
 *
 * ## v31 的做法
 *  · **闸门开着就让路**：不再看环里剩多少 —— 拖动期间那个位置本来就作废了。
 *  · **落点窗口在下也让路**：那一跳在关键路径上，它要独占源站带宽。
 *  · **让路就掐掉在飞的块**：只"不开新块"没用 ——
 *    已经开的那 4 MiB 会把封顶带宽吃光，落点那一跳只能拿到零头。
 *  · **一直让到闸门关**：不再有"环见底就恢复"这种提前放水的规则。
 */
internal class OriginYieldPolicy(
    /** 拖动让路闸（拖动期间打开，松手后自动失效）。 */
    private val gate: OriginYieldGate,
    /** 日志里的标签（`play` / `thumb`）。 */
    private val label: String,
    /** 落点窗口是不是正在下（那一跳要独占源站带宽）。 */
    private val landingInFlight: () -> Boolean,
    /** 掐掉在飞的块（把源站的封顶带宽让出来）。 */
    private val abortInFlight: () -> Unit,
) {
    /** 当前是不是在让路（只为"状态变化"记一行日志，不刷屏）。 */
    private var yielding = false

    /**
     * 这一轮要不要让路。
     *
     * @return true = 让路（生产循环这一轮什么也不做）。
     */
    fun shouldYield(): Boolean {
        val busy = gate.isYielding() || landingInFlight()
        if (busy) {
            if (!yielding) {
                yielding = true
                // 【为什么掐掉在飞的块】源站带宽是封顶的：
                // 已经开的那 4 MiB 不掐掉，落点那一跳只能拿到零头。
                abortInFlight()
                NetDiag.log("[$label] origin 让路：掐掉在飞的块（落点那一跳独占源站带宽）")
            }
            return true
        }
        if (yielding) {
            yielding = false
            NetDiag.log("[$label] origin 恢复预读（让路结束）")
        }
        return false
    }
}
